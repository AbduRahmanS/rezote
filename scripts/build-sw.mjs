// Generates the offline service worker (sw.js) for a built Rezote app.
// It precaches every static file of the client build, including the SPA shell
// prerendered by TanStack Start, so the app opens with no network after the
// first visit. The sync API (/api) is never cached.
//
// Usage: node scripts/build-sw.mjs apps/collecte/dist/client

import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const dir = process.argv[2];
if (!dir || !existsSync(dir)) {
  console.error("Usage: node scripts/build-sw.mjs <client build dir>");
  process.exit(2);
}

const SHELL = "/_shell.html";
const PRECACHED = /\.(html|js|css|svg|png|ico|webmanifest|json)$/;
const SKIP = new Set(["sw.js", "_headers", "_redirects", ".assetsignore", "wrangler.json"]);

function walk(d) {
  return readdirSync(d).flatMap((name) => {
    const path = join(d, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = walk(dir)
  .map((p) => "/" + relative(dir, p).split(sep).join("/"))
  .filter((url) => PRECACHED.test(url) && !SKIP.has(url.slice(1)) && !url.endsWith(".map"))
  .sort();

if (!files.includes(SHELL)) {
  console.error(`${SHELL} is missing in ${dir}: is SPA mode enabled in the TanStack Start plugin?`);
  process.exit(1);
}

const hash = createHash("sha256");
for (const url of files) hash.update(url).update(readFileSync(join(dir, url.slice(1))));
const version = hash.digest("hex").slice(0, 16);

const sw = `// Generated by scripts/build-sw.mjs. Do not edit.
const CACHE = "rezote-${version}";
const SHELL = ${JSON.stringify(SHELL)};
const FILES = ${JSON.stringify(files)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("rezote-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith("/api/")) return;
  if (req.mode === "navigate") {
    // Every page is the same client-rendered shell; serve it from the cache so the app opens offline.
    // Cloudflare redirects /_shell.html to /_shell, and browsers refuse a cached "redirected"
    // response for a navigation, so the cached copy is re-wrapped without that flag.
    event.respondWith(
      caches.match(SHELL).then((hit) =>
        hit ? (hit.redirected ? hit.blob().then((b) => new Response(b, { status: 200, headers: hit.headers })) : hit) : fetch(req),
      ),
    );
    return;
  }
  event.respondWith(caches.match(url.pathname).then((hit) => hit || fetch(req)));
});
`;

writeFileSync(join(dir, "sw.js"), sw);
console.log(`sw.js: ${files.length} files precached, version ${version}`);

// Security headers for the static files, from the same policy the Worker applies
// to HTML pages, with the hashes of the shell's inline bootstrap scripts.
const { inlineScriptHashes, securityHeaders } = await import("../packages/core/security.mjs");
const hashes = await inlineScriptHashes(readFileSync(join(dir, SHELL.slice(1)), "utf8"));
const lines = Object.entries(securityHeaders(hashes)).map(([k, v]) => `  ${k}: ${v}`);
writeFileSync(join(dir, "_headers"), `# Generated by scripts/build-sw.mjs. Do not edit.\n/*\n${lines.join("\n")}\n`);
console.log(`_headers: ${hashes.length} inline script hash(es) allowed in script-src`);
